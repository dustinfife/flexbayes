test_that("print uses a compact table and distinguishes prior sources", {
  p = prior_example()
  p = update(p, parameter = "x", belief(mean = 1.5), belief(sd = .91))
  p = update(p, parameter = "gb", belief(mean = 1))
  before = p
  output = capture.output({ result = print(p) })
  text = paste(output, collapse = "\n")
  expect_match(text, "Priors (rstanarm 2.32.2)", fixed = TRUE)
  expect_match(text, "Parameter.*Prior.*Source.*Beliefs")
  expect_match(text, "Normal(1.50, 0.91)", fixed = TRUE)
  expect_match(text, "Exponential(", fixed = TRUE)
  expect_match(text, "Backend default")
  expect_match(text, "Elicited*", fixed = TRUE)
  expect_match(text, "resolve underdetermined beliefs")
  expect_false(any(grepl("\\$|Beliefs for|Centered intercept", output)))
  expect_equal(result, before)
  expect_equal(p, before)
  expect_lte(max(nchar(output)), 80)
})

test_that("summary expands details and hides stable IDs", {
  p = prior_example()
  p = update(p, parameter = "x", belief(mean = 1), belief(sd = 2))
  p = update(p, parameter = "x", remove = 1, belief(mode = 3))
  expect_equal(vapply(p$beliefs$x, `[[`, integer(1), "id"), c(2L, 3L))
  output = paste(capture.output({ result = print(summary(p)) }), collapse = "\n")
  expect_match(output, "1. sd = 2", fixed = TRUE)
  expect_match(output, "2. mode = 3", fixed = TRUE)
  expect_false(grepl("\\[|Score:|Residual", output))
  expect_match(output, "Centered intercept reference")
  expect_match(output, "3.5")
  expect_equal(result$object, p)
  details = paste(capture.output(summary(p, diagnostics = TRUE)), collapse = "\n")
  expect_match(details, "Normal candidate: accepted")
  expect_match(details, "Target.*Achieved.*Tolerance.*Residual")
  q = update(p, parameter = "x", remove = 2)
  expect_equal(q$beliefs$x[[1]]$type, "sd")
  expect_equal(q$beliefs$x[[1]]$id, 2L)
  expect_length(q$beliefs$x, 1)
})

