test_that("resolved defaults agree with actual backend preprocessing", {
  p = prior_example()
  captured = new.env(parent = emptyenv())
  testthat::local_mocked_bindings(set_sampling_args = function(..., data) {
    captured$data = data
    stop("preprocessing captured")
