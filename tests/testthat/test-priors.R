test_that("Gaussian defaults match backend scaling and contrasts", {
  p = prior_example()
  sy = sd(p$model$frame$y)
  expect_equal(p$defaults$x$sd, 2.5 * sy / sd(1:6))
  expect_equal(p$defaults$gb$sd, 2.5 * sy / sd(rep(c(0, 1), 3)))
  expect_equal(p$defaults$`(Intercept)`$mean, mean(p$model$frame$y))
  expect_equal(p$defaults$sigma$rate, 1 / sy)
  expect_equal(unname(p$model$reference), c(3.5, .5))
  expect_equal(p$parameters$term, c(0L, 1L, 2L, NA_integer_))
  expect_s3_class(plot(p), "ggplot")
  expect_equal(summary(p)$object, p)
})

test_that("beliefs validate syntax and numeric targets", {
  expect_s3_class(belief(value > -2, probability = .9), "prior_belief")
  expect_error(belief(foo < 2, probability = .5))
  expect_error(belief(value < 2, probability = 1.1))
  expect_error(belief(sd = 0))
  expect_error(belief(mean = 1, mode = 2))
  expect_error(belief(value < "invalid", probability = .5))
})

test_that("normal constraints fit and updates preserve unrelated priors", {
  p = prior_example()
  q = update(p, parameter = "x", belief(mean = 2), belief(sd = .5))
  expect_equal(q$selected$x, list(distribution = "normal", mean = 2, sd = .5))
  expect_equal(p$beliefs$x, list())
  expect_equal(q$selected$gb, p$selected$gb)
  expect_true(q$candidates$x$valid)
  expect_false(q$candidates$x$reference_used)
  q = update(q, parameter = "x", remove = 1, belief(mode = 3))
  expect_equal(vapply(q$beliefs$x, `[[`, integer(1), "id"), c(2L, 3L))
  expect_equal(q$selected$x$mean, 3)
  q = update(q, parameter = "x", remove = c(1, 2))
  expect_equal(q$selected$x, p$defaults$x)
  expect_error(update(p, parameter = "x", remove = 1))
})

test_that("probability fitting and default reference are explicit", {
  p = prior_example()
  q = update(p, parameter = "x", belief(mean = 2))
  expect_equal(q$selected$x$sd, p$defaults$x$sd)
  expect_true(q$candidates$x$reference_used)
  q = update(p, parameter = "x", belief(value < 1, probability = pnorm(-1)), belief(mean = 2))
  expect_equal(q$selected$x$sd, 1, tolerance = 1e-8)
  q = update(p, parameter = "x", belief(value < 2, probability = .2), belief(mode = 2))
  expect_null(q$selected$x)
  expect_length(q$beliefs$x, 2)
  expect_error(plot(q), "No selected prior")
  q = update(p, parameter = "x", belief(mean = 1), belief(mean = 2))
  expect_false(q$candidates$x$valid)
})

