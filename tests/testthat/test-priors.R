  expect_equal(as.numeric(d$prior_scale), c(p$defaults$x$sd, p$defaults$gb$sd))
  expect_equal(as.numeric(d$prior_mean_for_intercept), p$defaults$`(Intercept)`$mean)
  expect_equal(as.numeric(d$prior_scale_for_intercept), p$defaults$`(Intercept)`$sd)
  expect_equal(as.numeric(d$prior_scale_for_aux), 1 / p$defaults$sigma$rate)
  expect_equal(as.numeric(d$xbar), unname(p$model$reference))
